#!/usr/bin/env python3
"""Build Apache RewriteMap text files from the manifest.

Writes into --out (default maps/):
    dc_paths.txt     "etd/123 https://..."   landing pages and series
    dc_article.txt   "etd/1124 https://..."  viewcontent.cgi and /context/... file URLs
    ark.txt          "32498/x7k9q https://..."
    stats.json       row counts and SHA-256 per map (the deploy script checks these)
    smoke_test.tsv   a random sample of real entries for post-deploy checks

Withdrawn items get the value GONE, which the Apache rules turn into 410 Gone.

Usage:
    python scripts/build_maps.py --dc-host scholarworks.uni.edu \
        --ark-host library.uni.edu --out maps/
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from manifest import GONE, build_maps, read_manifest  # noqa: E402


def write_map(path: Path, entries: dict[str, str]) -> str:
    lines = [f"{k} {v}\n" for k, v in sorted(entries.items())]
    text = "# Generated by build_maps.py - do not edit; change the manifest instead.\n" + "".join(lines)
    path.write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def smoke_rows(maps: dict[str, dict[str, str]], dc_host: str, ark_host: str, n: int, seed: int) -> list[tuple]:
    """Pick up to n entries from each map and the request that should hit them.

    Each row: host, path_and_query, expected_status, expected_location
    """
    rng = random.Random(seed)
    rows: list[tuple] = []

    def sample(entries: dict[str, str]):
        keys = sorted(entries)
        return rng.sample(keys, min(n, len(keys)))

    def expect(value: str):
        return ("410", "") if value == GONE else ("301", value)

    for key in sample(maps["dc_paths"]):
        status, loc = expect(maps["dc_paths"][key])
        rows.append((dc_host, f"/{key}/", status, loc))
    for key in sample(maps["dc_article"]):
        context, article = key.split("/", 1)
        status, loc = expect(maps["dc_article"][key])
        rows.append((dc_host, f"/cgi/viewcontent.cgi?article={article}&context={context}", status, loc))
        rows.append((dc_host, f"/context/{context}/article/{article}/viewcontent/file.pdf", status, loc))
    for key in sample(maps["ark"]):
        value = maps["ark"][key]
        status, loc = ("410", "") if value == GONE else ("302", value)
        rows.append((ark_host, f"/ark:/{key}", status, loc))
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default="manifest/redirects.csv")
    ap.add_argument("--overrides", default="manifest/overrides.csv")
    ap.add_argument("--out", default="maps")
    ap.add_argument("--dc-host", default=os.environ.get("DC_HOST", "scholarworks.example.edu"),
                    help="old Digital Commons hostname (for the smoke-test sample)")
    ap.add_argument("--ark-host", default=os.environ.get("ARK_HOST", ""),
                    help="ARK resolver hostname (defaults to --dc-host)")
    ap.add_argument("--sample", type=int, default=20, help="smoke-test entries per map")
    ap.add_argument("--seed", type=int, default=None, help="random seed for the sample")
    args = ap.parse_args()

    base = read_manifest(args.manifest)
    overrides = read_manifest(args.overrides)
    if not base and not overrides:
        print(f"warning: {args.manifest} and {args.overrides} have no rows; maps will be empty",
              file=sys.stderr)

    maps = build_maps(base, overrides)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    stats = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "commit": os.environ.get("CI_COMMIT_SHA", ""),
        "maps": {},
    }
    for name, entries in maps.items():
        digest = write_map(out / f"{name}.txt", entries)
        gone = sum(1 for v in entries.values() if v == GONE)
        stats["maps"][name] = {"entries": len(entries), "withdrawn": gone, "sha256": digest}
        print(f"{name}.txt: {len(entries)} entries ({gone} withdrawn)")

    (out / "stats.json").write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")

    seed = args.seed if args.seed is not None else int(datetime.now().timestamp())
    rows = smoke_rows(maps, args.dc_host, args.ark_host or args.dc_host, args.sample, seed)
    with (out / "smoke_test.tsv").open("w", encoding="utf-8") as fh:
        fh.write("# host\tpath\texpected_status\texpected_location\n")
        for row in rows:
            fh.write("\t".join(row) + "\n")
    print(f"smoke_test.tsv: {len(rows)} checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
